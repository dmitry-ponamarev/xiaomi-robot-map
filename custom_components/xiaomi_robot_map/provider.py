"""Retrieve the map for a vacuum.

Two sources are supported:

* **Cloud** (stock firmware): the Xiaomi cloud stores a vacuum map under a *map
  name* which is generated by the robot itself.  For Roborock devices the name
  has to be requested over the local miIO protocol (``get_map_v1``); once known,
  the cloud hands out a temporary download URL for the blob.
* **Local** (no Xiaomi account): the map is fetched from the robot or from a
  local service.  Two dialects are handled - Valetudo's JSON map
  (``GET /api/v2/robot/state/map``) and a raw RRMap blob served over HTTP.
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass
from typing import Any

import aiohttp
from homeassistant.core import HomeAssistant
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from . import miio_local
from .cloud import CloudDevice, XiaomiApiError, XiaomiCloudClient, XiaomiCloudError
from .const import LOCAL_KIND_RRMAP, LOCAL_KIND_VALETUDO, LOCAL_TIMEOUT

_LOGGER = logging.getLogger(__name__)

MAP_NAME_RETRIES = 4
MAP_NAME_RETRY_DELAY = 1.0
MAP_NAME_TIMEOUT = 6


class MapFetchError(XiaomiCloudError):
    """Raised when the map could not be retrieved."""


class MapNameUnavailable(MapFetchError):
    """Raised when the vacuum does not report a map name."""


@dataclass(slots=True)
class MapPayload:
    """A map as received from a source, plus the format it is encoded in."""

    raw: bytes
    map_name: str
    kind: str = LOCAL_KIND_RRMAP


def query_map_name(host: str, token: str, retries: int = MAP_NAME_RETRIES) -> str:
    """Ask the vacuum for its current map name (blocking, run in executor)."""
    last_error: Exception | None = None
    for attempt in range(retries):
        try:
            return miio_local.get_map_name(host, token, timeout=MAP_NAME_TIMEOUT)
        except miio_local.MiioTimeout as err:
            last_error = err
            _LOGGER.debug("Local map name request timed out (attempt %s/%s)", attempt + 1, retries)
        except (miio_local.MiioError, ValueError) as err:
            last_error = err
            _LOGGER.debug("Local map name request failed (attempt %s/%s): %s", attempt + 1, retries, err)
        if attempt + 1 < retries:
            time.sleep(MAP_NAME_RETRY_DELAY * (attempt + 1))
    if last_error is not None:
        raise MapNameUnavailable(f"unable to query the map name from {host}: {last_error}") from last_error
    raise MapNameUnavailable(f"the vacuum at {host} did not report a map name")


class MapFetcher:
    """Fetch the newest map for one vacuum from the Xiaomi cloud."""

    def __init__(
        self,
        hass: HomeAssistant,
        client: XiaomiCloudClient,
        *,
        host: str | None,
        token: str,
        country: str,
        user_id: str | None,
        device_id: str | None,
        map_name_override: str | None = None,
    ) -> None:
        self._hass = hass
        self._client = client
        self._host = host
        self._token = token
        self._country = country
        self._user_id = user_id
        self._device_id = device_id
        self._map_name_override = map_name_override
        self._cached_map_name: str | None = None
        self._cache_time = 0.0

    async def async_fetch(self) -> MapPayload:
        """Return the raw map blob, raising :class:`MapFetchError` on failure."""
        map_name = await self.async_get_map_name()
        device = CloudDevice(
            device_id=self._device_id or "",
            name="",
            model="",
            token=self._token,
            country=self._country,
            user_id=self._user_id,
        )
        url = await self._client.async_get_map_url(device, map_name)
        if not url:
            raise MapFetchError(f"the cloud did not provide a download URL for map '{map_name}'")
        raw = await self._client.async_download(url)
        if not raw:
            raise XiaomiApiError("the downloaded map is empty")
        return MapPayload(raw=raw, map_name=map_name)

    async def async_get_map_name(self) -> str:
        """Return the map object name, querying the robot when needed."""
        if self._map_name_override:
            return self._map_name_override
        if self._cached_map_name and time.monotonic() - self._cache_time < 30:
            return self._cached_map_name
        if not self._host:
            raise MapNameUnavailable("a vacuum host is required to read the map name")
        map_name = await self._hass.async_add_executor_job(query_map_name, self._host, self._token)
        self._cached_map_name = map_name
        self._cache_time = time.monotonic()
        return map_name

    def invalidate_cache(self) -> None:
        """Forget the cached map name (e.g. after a failed download)."""
        self._cached_map_name = None
        self._cache_time = 0.0


class LocalMapFetcher:
    """Fetch the map from the robot itself (Valetudo) or from a local URL."""

    def __init__(
        self,
        hass: HomeAssistant,
        *,
        url: str,
        kind: str,
        username: str | None = None,
        password: str | None = None,
        token: str | None = None,
    ) -> None:
        self._hass = hass
        self._url = url
        self._kind = kind or LOCAL_KIND_RRMAP
        self._username = username or None
        self._password = password or None
        self._token = token or None

    @property
    def kind(self) -> str:
        """Dialect served by this endpoint."""
        return self._kind

    @property
    def url(self) -> str:
        """Endpoint the map is fetched from."""
        return self._url

    async def async_fetch(self) -> MapPayload:
        """Download the map document; raises :class:`MapFetchError` on failure."""
        session = async_get_clientsession(self._hass)
        headers = {"Accept": "application/json, application/gzip, application/octet-stream"}
        auth = aiohttp.BasicAuth(self._username, self._password or "") if self._username else None
        if self._token:
            headers["Authorization"] = f"Bearer {self._token}"

        timeout = aiohttp.ClientTimeout(total=LOCAL_TIMEOUT)
        try:
            async with session.get(self._url, headers=headers, auth=auth, timeout=timeout) as response:
                if response.status in (401, 403):
                    raise MapFetchError(f"{self._url} requires authorisation (HTTP {response.status})")
                if response.status != 200:
                    raise MapFetchError(f"{self._url} answered with HTTP {response.status}")
                data = await response.read()
        except MapFetchError:
            raise
        except (aiohttp.ClientError, TimeoutError, OSError) as err:
            raise MapFetchError(f"unable to reach {self._url}: {err}") from err

        if not data:
            raise MapFetchError(f"{self._url} returned an empty body")
        return MapPayload(raw=data, map_name=self._url, kind=self._kind)

    def invalidate_cache(self) -> None:
        """Nothing to invalidate for a plain HTTP source."""


def parse_local_payload(payload: MapPayload) -> Any:
    """Parse a local payload into an RRMap (blocking, may run in an executor)."""
    from .rr_map import parse_rrmap
    from .valetudo_map import ValetudoMapError, parse_valetudo_map

    if payload.kind == LOCAL_KIND_VALETUDO:
        try:
            document = json.loads(payload.raw)
        except ValueError as err:
            raise ValetudoMapError(f"the answer is not valid JSON: {err}") from err
        return parse_valetudo_map(document)
    return parse_rrmap(payload.raw)
