"""Minimal miIO v1 client used to read the current map name.

The cloud can only hand out a map URL for a *map name* that is generated by the
robot, and the only way to learn it is the local ``get_map_v1`` command.  A full
miIO implementation (python-miio) drags in a lot of dependencies, so this module
implements just the two packets that are needed:

* the fixed 32 byte handshake, which returns the device id and clock,
* one AES-128-CBC encrypted JSON request/response pair.

The format is the reverse engineered protocol used by the Mi Home app; it is
also what python-miio implements in ``miio.protocol``.
"""

from __future__ import annotations

import hashlib
import json
import logging
import socket
import struct
import time
from typing import Any

from Crypto.Cipher import AES
from Crypto.Util.Padding import pad, unpad

_LOGGER = logging.getLogger(__name__)

PORT = 54321
MAGIC = b"\x21\x31"
HANDSHAKE = bytes.fromhex("21310020ffffffffffffffffffffffffffffffffffffffffffffffffffffffff")
HEADER_LENGTH = 16
CHECKSUM_LENGTH = 16
PACKET_OVERHEAD = HEADER_LENGTH + CHECKSUM_LENGTH
MAX_PACKET = 4096


class MiioError(Exception):
    """Base error for local miIO communication."""


class MiioTimeout(MiioError):
    """The device did not answer in time."""


class MiioProtocolError(MiioError):
    """The device answered with something that is not valid miIO."""


def _md5(data: bytes) -> bytes:
    return hashlib.md5(data).digest()  # noqa: S324 - protocol requirement


def _key_iv(token: bytes) -> tuple[bytes, bytes]:
    key = _md5(token)
    return key, _md5(key + token)


def encrypt(payload: bytes, token: bytes) -> bytes:
    """Encrypt a payload with the device token (AES-128-CBC, PKCS#7)."""
    key, iv = _key_iv(token)
    return AES.new(key, AES.MODE_CBC, iv).encrypt(pad(payload, AES.block_size))


def decrypt(payload: bytes, token: bytes) -> bytes:
    """Decrypt a payload with the device token."""
    key, iv = _key_iv(token)
    return unpad(AES.new(key, AES.MODE_CBC, iv).decrypt(payload), AES.block_size)


def build_handshake() -> bytes:
    """Return the fixed handshake packet."""
    return HANDSHAKE


def parse_handshake(data: bytes) -> tuple[bytes, int]:
    """Return ``(device_id, device_clock)`` from a handshake reply."""
    if len(data) != 32 or not data.startswith(MAGIC):
        raise MiioProtocolError(f"unexpected handshake reply: {data[:8].hex()}")
    device_id = data[8:12]
    timestamp = struct.unpack(">I", data[12:16])[0]
    return device_id, timestamp


def build_command(device_id: bytes, timestamp: int, payload: dict[str, Any], token: bytes) -> bytes:
    """Build an encrypted command packet."""
    body = json.dumps(payload, separators=(",", ":")).encode() + b"\x00"
    encrypted = encrypt(body, token)
    header = struct.pack(">HHI", 0x2131, PACKET_OVERHEAD + len(encrypted), 0) + device_id + struct.pack(">I", timestamp & 0xFFFFFFFF)
    checksum = _md5(header + token + encrypted)
    return header + checksum + encrypted


def parse_command(data: bytes, token: bytes) -> dict[str, Any]:
    """Validate and decrypt a command reply."""
    if len(data) < PACKET_OVERHEAD or not data.startswith(MAGIC):
        raise MiioProtocolError("unexpected response packet")
    length = struct.unpack(">H", data[2:4])[0]
    if length != len(data):
        raise MiioProtocolError(f"packet length mismatch: header says {length}, got {len(data)}")
    header = data[:HEADER_LENGTH]
    checksum = data[HEADER_LENGTH:PACKET_OVERHEAD]
    encrypted = data[PACKET_OVERHEAD:]
    if checksum != _md5(header + token + encrypted):
        raise MiioProtocolError("checksum mismatch in the device response")
    try:
        plaintext = decrypt(encrypted, token)
    except ValueError as err:
        raise MiioProtocolError(f"unable to decrypt the response: {err}") from err
    try:
        return json.loads(plaintext.rstrip(b"\x00").decode("utf-8"))
    except ValueError as err:
        raise MiioProtocolError(f"unable to decode the response: {err}") from err


def send_command(
    host: str,
    token: bytes,
    method: str,
    params: list[Any] | None = None,
    timeout: float = 5.0,
    port: int = PORT,
) -> Any:
    """Perform a handshake and send a single command (blocking)."""
    if len(token) != 16:
        raise ValueError("the device token must be 16 bytes")
    params = params or []
    air = (host, port)
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.settimeout(timeout)
        try:
            sock.sendto(build_handshake(), air)
            reply, _ = sock.recvfrom(MAX_PACKET)
        except TimeoutError as err:
            raise MiioTimeout(f"no handshake reply from {host}:{port}") from err
        except OSError as err:
            raise MiioError(f"unable to reach {host}:{port}: {err}") from err

        device_id, timestamp = parse_handshake(reply)
        request = {
            "id": int(time.time()) & 0xFFFF,
            "method": method,
            "params": params,
        }
        packet = build_command(device_id, timestamp + 1, request, token)
        try:
            sock.sendto(packet, air)
            response, _ = sock.recvfrom(MAX_PACKET)
        except TimeoutError as err:
            raise MiioTimeout(f"no reply to {method} from {host}:{port}") from err
        except OSError as err:
            raise MiioError(f"unable to reach {host}:{port}: {err}") from err

    message = parse_command(response, token)
    error = message.get("error")
    if isinstance(error, dict) and error.get("code"):
        raise MiioProtocolError(f"{method} failed: {error.get('message') or error}")
    return message.get("result")


def extract_map_name(result: Any) -> str | None:
    """Normalise the ``get_map_v1`` result into a map name."""
    value: Any = result
    if isinstance(result, (list, tuple)):
        value = result[0] if result else None
    if isinstance(value, bytes):
        value = value.decode("ascii", "ignore")
    if value is None:
        return None
    text = str(value).strip()
    if not text or text.lower() in {"retry", "none", "null", "error"}:
        return None
    return text


def get_map_name(host: str, token_hex: str, timeout: float = 5.0, port: int = PORT) -> str:
    """Return the current map name, raising :class:`MiioError` on failure."""
    try:
        token = bytes.fromhex(token_hex)
    except ValueError as err:
        raise ValueError(f"invalid token: {err}") from err
    result = send_command(host, token, "get_map_v1", timeout=timeout, port=port)
    map_name = extract_map_name(result)
    if map_name is None:
        raise MiioProtocolError(f"device returned no map name (result: {result!r})")
    return map_name
